// Compiles content/guides/*.md into lib/guides-data.ts (runs before every build).
import { readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs';
const dir = new URL('../content/guides/', import.meta.url);
const out = readdirSync(dir).filter((f) => f.endsWith('.md')).sort().map((f) => {
  const raw = readFileSync(new URL(f, dir), 'utf8');
  const m = raw.match(/^---json\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`Bad frontmatter in ${f}`);
  const meta = JSON.parse(m[1]);
  return { slug: f.replace(/\.md$/, ''), updated: meta.updated || statSync(new URL(f, dir)).mtime.toISOString().slice(0, 10), ...meta, body: m[2].trim() };
});
writeFileSync(new URL('../lib/guides-data.ts', import.meta.url),
  `// AUTO-GENERATED by scripts/build-guides.mjs from content/guides. Do not edit by hand.\nexport const GUIDE_DATA = ${JSON.stringify(out, null, 1)} as const;\n`);
console.log(`guides: ${out.length}`);
